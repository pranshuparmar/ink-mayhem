package com.pranshuparmar.inkmayhem.game

import com.pranshuparmar.inkmayhem.physics.Ink

/** World 4, The Castle: brickwork. Boulders, seesaws over spikes, crumbling bricks; ink beetles; the Gold nib. */
object World4 {
    /**
     * World 4's teaching page, in the castle. What's new waits for you on the first run: a boulder
     * runway (only rope lets the boulder drop), a crumbling bridge (don't stop), a beetle pit
     * (beetles eat rope and springs; a beam they can't bite), and the Gold nib.
     */
    val CASTLE_GATE = StageDef(4, 1, "Castle Gate", Theme.CASTLE, 3.8f) {
        start(16f)
        note("The castle. Spikes below, spikes above.", dx = -14f, maxW = 6f)
        stars(x - 10f, 5)
        starLine(x + 0.6f, level - 0.65f, x + 2.9f, level - 0.65f, 3)
        spikePit(3.5f)
        flat(8f)
        tunnel(4.5f)
        flat(10f)
        // a boulder runway: rope lets the boulder drop through, anything else carries it after you
        note("A boulder will roll after you. Rope across the gap lets it fall; a beam or a spring would carry it.", dx = -9f, up = 4.2f, maxW = 8f)
        val r0 = x
        hint(Ink.ROPE, r0 + 17f, r0 + 23f, r0 + 17.9f, level - 0.05f, r0 + 23.1f, level - 0.05f, waitX = r0 + 2f, needs = Ink.ROPE)
        runway(18f)
        gap(5f, HazardType.BOULDER)
        flat(10f)
        // a crumbling bridge
        note("Crumbling bricks fall a moment after you roll on. Keep going!", dx = -8f, maxW = 6f)
        crumbleBridge(6f)
        flat(10f)
        drops(x - 7f, 3)
        checkpoint()
        flat(8f)
        // a beetle pit
        note("Ink beetles eat rope and springs. A beam they can't bite.", dx = -7f, up = 3.6f, maxW = 7f)
        hint(Ink.BEAM, x - 1f, x + 5f, x - 0.1f, level - 0.05f, x + 5.1f, level - 0.05f, waitX = x - 1.4f, needs = Ink.BEAM)
        beetlePit(5f)
        flat(10f)
        // the Gold nib: free ink that never snaps, and beetles can't bite it
        val bx = x - 5f
        note("A doodle box: spring up into it.", dx = -11f, up = 5.4f, maxW = 6f)
        box(bx, up = 2.6f, holds = ItemKind.GOLD_NIB)
        springOn(bx - 0.5f, lead = 4f)
        flat(6f)
        note("Gold nib: free ink, it never snaps, and beetles can't bite it.", dx = -4f, up = 4.2f, maxW = 7f)
        beetlePit(5f, beetles = 2, solve = Ink.ROPE)
        flat(3f)
        beetlePit(5f, solve = Ink.ROPE)
        flat(10f)
        bounceGold(x - 8f)
        seesawGap(6f, spikesBelow = true)
        flat(8f)
        wall(2.4f)
        flat(14f)
        highRoad(x - 8f, 6f)
        gold(x - 4f, level - 3.8f)
        heart(x - 3f, level - 3.8f)
        flat(4f)
        spikePit(7.6f, type = HazardType.GAP_L)
        flat(10f)
        bounceGold(x - 8f)
        flat(2f)
        finish()
    }

    /** Boulders: one runway after another, each ending in a gap only rope lets them fall through. */
    val ROLLING_STONES = StageDef(4, 2, "Rolling Stones", Theme.CASTLE, 3.8f) {
        start(14f)
        note("Boulders all the way. Rope lets them drop.", dx = -12f, maxW = 6f)
        runway(18f)
        starLine(x + 0.8f, level - 0.65f, x + 4.2f, level - 0.65f, 4)
        gap(5f, HazardType.BOULDER)
        flat(10f)
        bounceGold(x - 8f)
        spikePit(4f)
        flat(6f)
        runway(18f)
        spikePit(5f, type = HazardType.BOULDER)
        flat(10f)
        checkpoint()
        flat(6f)
        tunnel(4.5f)
        flat(10f)
        runway(20f)
        gap(5.5f, HazardType.BOULDER)
        flat(12f)
        highRoad(x - 8f, 6f)
        gold(x - 4f, level - 3.8f)
        heart(x - 3f, level - 3.8f)
        flat(4f)
        seesawGap(6f, spikesBelow = true)
        flat(8f)
        runway(18f)
        spikePit(5f, type = HazardType.BOULDER)
        flat(10f)
        bounceGold(x - 8f)
        flat(2f)
        finish()
    }

    /** Crumbling bricks: bridges of them, longer each time, and one into a wall you must spring over. */
    val CRUMBLE_KEEP = StageDef(4, 3, "Crumble Keep", Theme.CASTLE, 3.8f) {
        start(14f)
        note("Bricks that crumble behind you. Don't stop.", dx = -12f, maxW = 6f)
        crumbleBridge(4.8f)
        flat(8f)
        stars(x - 6f, 4)
        crumbleBridge(7.2f)
        flat(10f)
        bounceGold(x - 8f)
        spikePit(4f)
        flat(8f)
        crumbleBridge(9.6f)
        flat(10f)
        checkpoint()
        flat(6f)
        // a crumbling bridge with the gap after it: bridge it before you get there
        crumbleBridge(6f)
        flat(3f)
        gap(4.5f)
        flat(10f)
        wall(2.4f)
        flat(14f)
        highRoad(x - 8f, 6f)
        gold(x - 4f, level - 3.8f)
        heart(x - 3f, level - 3.8f)
        flat(4f)
        crumbleBridge(8.4f)
        flat(4f)
        tunnel(4.5f)
        // (the gold's spring clear of the tunnel's overhanging rock)
        flat(14f)
        bounceGold(x - 8f)
        flat(2f)
        finish()
    }

    /** Ink beetles in every pit: beams they can't bite, rope you'd have to race across, and the Gold nib. */
    val BEETLE_BRIDGES = StageDef(4, 4, "Beetle Bridges", Theme.CASTLE, 3.8f) {
        start(14f)
        note("Beetle pits. Beams, or the Gold nib.", dx = -12f, maxW = 6f)
        beetlePit(5f)
        flat(8f)
        stars(x - 6f, 4)
        // beams cost plenty of ink: drops between the pits
        drops(x - 6f, 3, up = 0.75f)
        beetlePit(6f, beetles = 2)
        flat(10f)
        drops(x - 8f, 3, up = 0.75f)
        bounceGold(x - 8f)
        spikePit(4f)
        flat(8f)
        checkpoint()
        flat(4f)
        val bx = x - 2f
        box(bx, up = 2.6f, holds = ItemKind.GOLD_NIB)
        springOn(bx - 0.5f, lead = 4f)
        flat(6f)
        beetlePit(5f, beetles = 2, solve = Ink.ROPE)
        flat(3f)
        beetlePit(6f, beetles = 2, solve = Ink.ROPE)
        flat(3f)
        beetlePit(5f, solve = Ink.ROPE)
        flat(12f)
        highRoad(x - 8f, 6f)
        gold(x - 4f, level - 3.8f)
        heart(x - 3f, level - 3.8f)
        dropAt(x - 6f, level - 3.95f)
        dropAt(x - 5f, level - 3.95f)
        flat(4f)
        beetlePit(7.6f, beetles = 2)
        flat(10f)
        bounceGold(x - 8f)
        flat(2f)
        finish()
    }

    /** The world's finale: a run through the castle, then the Beetle Queen, who lays beetles. Bounce on her. */
    val THE_BEETLE_QUEEN = StageDef(4, 5, "The Beetle Queen", Theme.CASTLE, 3.8f) {
        start(14f)
        note("The Beetle Queen waits in the keep. Bounce on her.", dx = -12f, maxW = 7f)
        spikePit(4f)
        flat(8f)
        runway(18f)
        gap(5f, HazardType.BOULDER)
        flat(10f)
        bounceGold(x - 8f)
        crumbleBridge(6f)
        flat(8f)
        beetlePit(5f)
        flat(14f)
        highRoad(x - 8f, 6f)
        gold(x - 4f, level - 3.8f)
        heart(x - 3f, level - 3.8f)
        flat(4f)
        seesawGap(6f, spikesBelow = true)
        flat(10f)
        bounceGold(x - 7.5f)
        flat(2f)
        checkpoint()
        flat(10f)
        arena(BossKind.BEETLE_QUEEN)
        flat(6f)
        finish()
    }

    val STAGES = listOf(CASTLE_GATE, ROLLING_STONES, CRUMBLE_KEEP, BEETLE_BRIDGES, THE_BEETLE_QUEEN)
}
