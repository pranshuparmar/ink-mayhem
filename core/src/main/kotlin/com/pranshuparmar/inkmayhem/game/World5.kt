package com.pranshuparmar.inkmayhem.game

import com.pranshuparmar.inkmayhem.physics.Ink

/** World 5, Midnight Ink: an ink-soaked page drawn in pale ink. The ink tide, ink pools; the Star nib; the Big Smudge. */
object World5 {
    /**
     * World 5's teaching page, at midnight. What's new waits for you on the first run: an ink pool
     * (it swallows ink too, so a bridge has to stay above it), the Star nib (nothing hurts while it
     * lasts) and, last, the ink tide, which chases you and never stops.
     */
    val LIGHTS_OUT = StageDef(5, 1, "Lights Out", Theme.MIDNIGHT, 3.8f) {
        start(16f)
        note("Midnight. The whole page is soaked in ink.", dx = -14f, maxW = 6f)
        stars(x - 10f, 5)
        starLine(x + 0.6f, level - 0.65f, x + 2.9f, level - 0.65f, 3)
        spikePit(3.5f)
        flat(8f)
        wall(2.4f)
        flat(12f)
        // an ink pool: it swallows whatever touches it, ink too
        note("Ink pools swallow anything that touches them, even ink. Keep your bridge tight, above the ink.", dx = -10f, up = 4.2f, maxW = 8f)
        hint(Ink.ROPE, x - 1f, x + 4.5f, x - 0.1f, level - 0.05f, x + 4.6f, level - 0.05f, waitX = x - 1.4f)
        inkPool(4.5f)
        flat(10f)
        bounceGold(x - 8f)
        starLine(x + 0.6f, level - 0.65f, x + 3.4f, level - 0.65f, 3)
        inkPool(4f)
        flat(3f)
        inkPool(4f)
        flat(10f)
        drops(x - 7f, 3)
        checkpoint()
        flat(8f)
        // the Star nib
        val bx = x - 3f
        note("A doodle box: spring up into it.", dx = -9f, up = 5.4f, maxW = 6f)
        box(bx, up = 2.6f, holds = ItemKind.STAR_NIB)
        hint(Ink.SPRING, bx - 2f, bx + 1f, bx - 0.5f, level - 0.1f, bx + 0.3f, level - 0.1f, waitX = bx - 4.5f)
        springOn(bx - 0.5f, lead = 4f)
        flat(8f)
        note("Star nib: nothing can hurt you. Roll right through them!", dx = -6f, up = 4.2f, maxW = 7f)
        val c0 = x + 6f
        blot(c0)
        eraser(c0 + 4f)
        blot(c0 + 7f)
        beetle(c0 + 10f)
        blot(c0 + 12f)
        stars(c0 - 2f, 9, gap = 1.6f)
        flat(26f)
        // the ink tide
        note("The ink tide! It never stops, so neither can you.", dx = -8f, maxW = 6f)
        tideStart()
        flat(8f)
        gap(4.5f)
        flat(6f)
        wall(2.4f)
        flat(8f)
        spikePit(4f)
        flat(14f)
        highRoad(x - 8f, 6f)
        gold(x - 4f, level - 3.8f)
        heart(x - 3f, level - 3.8f)
        flat(4f)
        inkPool(4.5f)
        flat(10f)
        bounceGold(x - 8f)
        tideEnd()
        flat(2f)
        finish()
    }

    /** The tide all the way: two long chases over gaps, climbs, a tunnel and crumbling bricks. Draw ahead. */
    val TIDE_RUN = StageDef(5, 2, "Tide Run", Theme.MIDNIGHT, 3.9f) {
        start(14f)
        note("The tide is coming. Don't stop for anything.", dx = -12f, maxW = 6f)
        tideStart()
        flat(6f)
        starLine(x + 0.6f, level - 0.65f, x + 3.9f, level - 0.65f, 4)
        gap(4.5f)
        flat(6f)
        climb(2)
        spikePit(4.5f)
        flat(6f)
        tunnel(4.5f)
        flat(14f)
        bounceGold(x - 8f)
        crumbleBridge(6f)
        flat(8f)
        drops(x - 6f, 3)
        tideEnd()
        flat(6f)
        checkpoint()
        flat(8f)
        tideStart()
        flat(6f)
        seesawGap(6f, spikesBelow = true)
        flat(14f)
        highRoad(x - 8f, 6f)
        gold(x - 4f, level - 3.8f)
        heart(x - 3f, level - 3.8f)
        flat(4f)
        inkPool(4.5f)
        flat(6f)
        slope(10f, -2.4f)
        flat(6f)
        gap(7.6f, HazardType.GAP_L)
        flat(8f)
        wall(2.4f)
        flat(10f)
        bounceGold(x - 8f)
        tideEnd()
        flat(2f)
        finish()
    }

    /** Ink pools: island to island across the sea, down sloping bridges, up with a spring, and a beam over the widest. */
    val INK_SEA = StageDef(5, 3, "Ink Sea", Theme.MIDNIGHT, 3.8f) {
        start(14f)
        note("The ink sea. Island to island, and never touch the ink.", dx = -12f, maxW = 7f)
        inkPool(4f)
        flat(3f)
        inkPool(4.5f)
        flat(3f)
        inkPool(4f)
        flat(8f)
        stars(x - 6f, 4)
        // down to lower islands: sloping bridges
        inkPool(4f, drop = 2f)
        flat(4f)
        inkPool(4f, drop = 2f)
        flat(10f)
        bounceGold(x - 8f)
        // up onto a higher island: spring across
        note("A higher island: spring across.", dx = -6f, maxW = 6f)
        poolWall()
        flat(8f)
        drops(x - 6f, 3)
        checkpoint()
        flat(6f)
        // too wide for rope
        note("Too wide for rope. A beam doesn't sag.", dx = -6f, maxW = 6f)
        inkPool(7.6f, type = HazardType.GAP_L)
        flat(8f)
        pool(x, 6f)
        seesawGap(6f)
        flat(14f)
        highRoad(x - 8f, 6f)
        gold(x - 4f, level - 3.8f)
        heart(x - 3f, level - 3.8f)
        flat(4f)
        inkPool(4.5f)
        flat(4f)
        poolWall()
        flat(6f)
        inkPool(4f, drop = 2.4f)
        flat(10f)
        bounceGold(x - 8f)
        flat(2f)
        finish()
    }

    /** Everything that walks the page: Blots, Erasers, beetles and paper planes, and a Star nib for the crowd. */
    val ALL_HANDS = StageDef(5, 4, "All Hands", Theme.MIDNIGHT, 3.9f) {
        start(14f)
        note("Everything that walks the page, all at once.", dx = -12f, maxW = 7f)
        // Blots: one bounce for both
        val b1 = x + 14f
        blot(b1)
        blot(b1 + 1.3f)
        springOn(b1 - 8.1f, lead = 4f)
        flat(28f)
        // an Eraser: drop a beam on it
        val e1 = x - 2f
        eraser(e1)
        solve(e1 - 0.9f, level - 3f, e1 + 0.9f, level - 3f, Ink.BEAM, lead = 19f)
        flat(10f)
        // beetles: a beam they can't bite
        drops(x - 6f, 3)
        beetlePit(5f)
        flat(10f)
        bounceGold(x - 8f)
        // paper planes: spring through them
        val p1 = x + 2f
        flat(14f)
        planes(p1)
        springOn(p1 + 3.4f, lead = 4f)
        flat(4f)
        drops(x - 4f, 3)
        checkpoint()
        flat(6f)
        // the Star nib, and a crowd
        val bx = x - 3f
        box(bx, up = 2.6f, holds = ItemKind.STAR_NIB)
        springOn(bx - 0.5f, lead = 4f)
        flat(8f)
        note("Star nib: zap the lot!", dx = -4f, up = 4.2f, maxW = 6f)
        val c0 = x + 6f
        blot(c0)
        eraser(c0 + 3f)
        beetle(c0 + 6f)
        blot(c0 + 8f)
        eraser(c0 + 11f)
        blot(c0 + 13f)
        planes(c0 - 2f, count = 3, gap = 1.6f)
        flat(28f)
        highRoad(x - 8f, 6f)
        gold(x - 4f, level - 3.8f)
        heart(x - 3f, level - 3.8f)
        flat(4f)
        // an Eraser walks off the edge: let it fall, then bridge
        val g1 = x
        gap(4f, lead = 3.5f)
        eraser(g1 + 4f + 1.5f)
        flat(12f)
        beetlePit(6f, beetles = 2)
        flat(12f)
        bounceGold(x - 8f)
        flat(2f)
        finish()
    }

    /** The world's finale: a run with the tide at your back and over the sea, then the Big Smudge. Spring it into its spiked roof. */
    val THE_BIG_SMUDGE = StageDef(5, 5, "The Big Smudge", Theme.MIDNIGHT, 3.9f) {
        start(14f)
        note("The Big Smudge waits at the end of the night.", dx = -12f, maxW = 7f)
        tideStart()
        flat(4f)
        inkPool(4.5f)
        flat(8f)
        wall(2.4f)
        flat(8f)
        drops(x - 6f, 3)
        beetlePit(5f)
        flat(10f)
        bounceGold(x - 8f)
        tideEnd()
        flat(6f)
        inkPool(4f)
        flat(3f)
        inkPool(4f)
        flat(14f)
        highRoad(x - 8f, 6f)
        gold(x - 4f, level - 3.8f)
        heart(x - 3f, level - 3.8f)
        flat(4f)
        gap(7.6f, HazardType.GAP_L)
        flat(10f)
        bounceGold(x - 7.5f)
        flat(2f)
        checkpoint()
        flat(10f)
        note("Spring it up into its spiked roof!", dx = -8f, maxW = 6f)
        arena(BossKind.BIG_SMUDGE)
        flat(6f)
        finish()
    }

    val STAGES = listOf(LIGHTS_OUT, TIDE_RUN, INK_SEA, ALL_HANDS, THE_BIG_SMUDGE)
}
